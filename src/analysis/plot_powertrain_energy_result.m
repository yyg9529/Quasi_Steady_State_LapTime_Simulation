function fig = plot_powertrain_energy_result(result)
%PLOT_POWERTRAIN_ENERGY_RESULT Plot node and segment engineering outputs.

arguments
    result (1,1) struct
end

activeNames = ["lateral", "brake", "traction", "motor_torque", ...
    "motor_power", "motor_speed", "motor_voltage", "rule_power", ...
    "rule_current", "battery_power", "battery_current", ...
    "inverter_power", "inverter_current", "top_speed"];
validateResult(result, activeNames);

s_m = result.s_m(:);
fig = figure(Name="Powertrain and Energy Result");
layout = tiledlayout(fig, 5, 2, Padding="compact", ...
    TileSpacing="compact");

ax = nexttile(layout);
yyaxis(ax, "left");
plot(ax, s_m, result.v_mps(:), LineWidth=1.2, ...
    DisplayName="Speed (m/s)");
ylabel(ax, "Speed (m/s)");
yyaxis(ax, "right");
hold(ax, "on");
plot(ax, s_m, result.ax_mps2(:), LineWidth=1.2, ...
    DisplayName="Ax (m/s^2)");
plot(ax, s_m, result.ay_mps2(:), LineWidth=1.2, ...
    DisplayName="Ay (m/s^2)");
ylabel(ax, "Acceleration (m/s^2)");
xlabel(ax, "Distance (m)");
grid(ax, "on");
title(ax, "Speed and Acceleration");
legend(ax, Location="best");

ax = nexttile(layout);
plot(ax, s_m, result.track.kappa_1pm(:), LineWidth=1.2, ...
    DisplayName="Curvature");
finishDistanceAxes(ax, "Curvature", "Curvature (1/m)");

ax = nexttile(layout);
limiter = string(result.limiter(:));
[limiterNames, ~, limiterCode] = unique(limiter, "stable");
stairs(ax, s_m, limiterCode, LineWidth=1.2, ...
    DisplayName="Primary limiter");
yticks(ax, 1:numel(limiterNames));
yticklabels(ax, limiterNames);
finishDistanceAxes(ax, "Primary Limiter", "Limiter");

ax = nexttile(layout);
activeMatrix = false(numel(activeNames), numel(s_m));
for index = 1:numel(activeNames)
    activeMatrix(index, :) = ...
        result.active_constraints.(activeNames(index))(:).';
end
imagesc(ax, s_m, 1:numel(activeNames), activeMatrix, ...
    Tag="active-constraints");
yticks(ax, 1:numel(activeNames));
yticklabels(ax, activeNames);
clim(ax, [0 1]);
colormap(ax, [1 1 1; 0.1 0.45 0.8]);
finishDistanceAxes(ax, "Active Constraints", "Constraint");

ax = nexttile(layout);
plot(ax, s_m, result.powertrain.motor_speed_rpm(:), ...
    LineWidth=1.2, DisplayName="Motor speed");
finishDistanceAxes(ax, "Motor Speed", "Motor speed (rpm)");

ax = nexttile(layout);
plot(ax, s_m, result.powertrain.motor_torque_used_Nm(:), ...
    LineWidth=1.2, DisplayName="Requested/used torque");
hold(ax, "on");
plot(ax, s_m, result.powertrain.motor_torque_available_Nm(:), ...
    LineWidth=1.2, DisplayName="Available torque");
finishDistanceAxes(ax, "Motor Torque", "Motor torque (N m)");
legend(ax, Location="best");

ax = nexttile(layout);
plot(ax, s_m, result.powertrain.tsac_power_used_W(:), ...
    LineWidth=1.2, DisplayName="TSAC power used");
hold(ax, "on");
plot(ax, s_m, result.powertrain.tsac_power_cap_W(:), ...
    LineWidth=1.2, DisplayName="TSAC power available");
plot(ax, [s_m(1) s_m(end)], [80e3 80e3], "--", ...
    LineWidth=1.1, Tag="fsg-rule-power", ...
    DisplayName="FSG rule reference (80 kW)");
finishDistanceAxes(ax, "TSAC Power", "Power (W)");
legend(ax, Location="best");

ax = nexttile(layout);
plot(ax, s_m, result.powertrain.tsac_dc_current_used_A(:), ...
    LineWidth=1.2, DisplayName="TSAC DC current used");
hold(ax, "on");
plot(ax, [s_m(1) s_m(end)], [500 500], "--", ...
    LineWidth=1.1, Tag="fsg-rule-current", ...
    DisplayName="FSG rule reference (500 A)");
finishDistanceAxes(ax, "TSAC Current", "Current (A)");
legend(ax, Location="best");

ax = nexttile(layout);
segmentDistance_m = [0; cumsum(result.track.ds_m(:))];
plot(ax, segmentDistance_m, ...
    result.energy.cumulative_energy_ts_kWh(:), LineWidth=1.2, ...
    Tag="cumulative-energy", DisplayName="Cumulative TSAC energy");
finishDistanceAxes(ax, "Cumulative Lap Energy", "Energy (kWh)");

ax = nexttile(layout);
usage = summarize_limiter_usage(result);
shareBar = bar(ax, 1:height(usage), usage.percent_distance, ...
    Tag="limiter-share", DisplayName="Distance share");
shareBar.FaceColor = [0.1 0.45 0.8];
xticks(ax, 1:height(usage));
xticklabels(ax, usage.limiter);
xtickangle(ax, 30);
finishDistanceAxes(ax, "Limiter Distance Share", ...
    "Distance share (%)");
end

function finishDistanceAxes(ax, titleText, yLabelText)
grid(ax, "on");
xlabel(ax, "Distance (m)");
ylabel(ax, yLabelText);
title(ax, titleText);
end

function validateResult(result, activeNames)
requiredTop = ["s_m", "v_mps", "ax_mps2", "ay_mps2", ...
    "limiter", "track", "powertrain", "energy", ...
    "active_constraints"];
requiredTrack = ["s_m", "ds_m", "kappa_1pm", "is_closed"];
requiredPowertrain = ["motor_speed_rpm", "motor_torque_used_Nm", ...
    "motor_torque_available_Nm", "tsac_power_used_W", ...
    "tsac_power_cap_W", "tsac_dc_current_used_A"];
if ~all(isfield(result, cellstr(requiredTop))) ...
        || ~isstruct(result.track) || ~isscalar(result.track) ...
        || ~all(isfield(result.track, cellstr(requiredTrack))) ...
        || ~isstruct(result.powertrain) || ~isscalar(result.powertrain) ...
        || ~all(isfield(result.powertrain, cellstr(requiredPowertrain))) ...
        || ~isstruct(result.energy) || ~isscalar(result.energy) ...
        || ~isfield(result.energy, "cumulative_energy_ts_kWh") ...
        || ~isstruct(result.active_constraints) ...
        || ~isscalar(result.active_constraints) ...
        || ~isequal(sort(string(fieldnames(result.active_constraints))), ...
            sort(activeNames(:)))
    error("QSSLTS:PlotResultContract", ...
        "The T5 powertrain, energy, and active-constraint contract is required.");
end

nPoint = numel(result.s_m);
isClosed = result.track.is_closed;
if nPoint < 2 || ~isscalar(isClosed) ...
        || ~ismember(double(isClosed), [0 1]) ...
        || numel(result.track.ds_m) ...
            ~= nPoint - 1 + double(logical(isClosed)) ...
        || numel(result.energy.cumulative_energy_ts_kWh) ...
            ~= numel(result.track.ds_m) + 1
    error("QSSLTS:PlotResultShape", ...
        "Node, segment, and cumulative-energy dimensions are inconsistent.");
end

nodeValues = {result.s_m, result.v_mps, result.ax_mps2, ...
    result.ay_mps2, result.track.s_m, result.track.kappa_1pm, ...
    result.powertrain.motor_speed_rpm, ...
    result.powertrain.motor_torque_used_Nm, ...
    result.powertrain.motor_torque_available_Nm, ...
    result.powertrain.tsac_power_used_W, ...
    result.powertrain.tsac_power_cap_W, ...
    result.powertrain.tsac_dc_current_used_A};
for index = 1:numel(nodeValues)
    value = nodeValues{index};
    if ~isnumeric(value) || ~isreal(value) || ~isvector(value) ...
            || numel(value) ~= nPoint || any(~isfinite(value(:)))
        error("QSSLTS:PlotResultShape", ...
            "Every plotted node field must be a finite vector of length N.");
    end
end
if any(diff(result.s_m(:)) <= 0) ...
        || ~isequaln(result.s_m(:), result.track.s_m(:)) ...
        || ~isnumeric(result.track.ds_m) ...
        || any(~isfinite(result.track.ds_m(:))) ...
        || any(result.track.ds_m(:) <= 0) ...
        || ~isnumeric(result.energy.cumulative_energy_ts_kWh) ...
        || any(~isfinite(result.energy.cumulative_energy_ts_kWh(:))) ...
        || numel(result.limiter) ~= nPoint ...
        || any(strlength(string(result.limiter(:))) == 0)
    error("QSSLTS:PlotResultShape", ...
        "Distance, limiter, or cumulative-energy data are invalid.");
end
for index = 1:numel(activeNames)
    value = result.active_constraints.(activeNames(index));
    if ~islogical(value) || ~isequal(size(value), [nPoint 1])
        error("QSSLTS:PlotResultShape", ...
            "Every active constraint must be an N-by-1 logical vector.");
    end
end
end
