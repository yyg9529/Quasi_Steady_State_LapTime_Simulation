classdef qssConsistencyTest < matlab.unittest.TestCase
    properties (SetAccess = private)
        CoarseResult
        FineResult
        MirrorResult
        CoarseGgv
        AxMinimum_mps2
        AxMaximum_mps2
        IsFeasible
        IsAtLongitudinalBoundary
        ReportsLongitudinalLimiter
    end

    methods (TestClassSetup)
        function buildReferenceResults(testCase)
            projectRoot = fileparts(fileparts(fileparts( ...
                mfilename("fullpath"))));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(projectRoot, "src"), IncludingSubfolders=true));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(projectRoot, "data"), IncludingSubfolders=true));
            testCase.applyFixture(matlab.unittest.fixtures.PathFixture( ...
                fullfile(projectRoot, "preprocessing"), ...
                IncludingSubfolders=true));

            track = read_track_csv(fullfile(projectRoot, "data", ...
                "track", "simple_track.csv"));
            vehicle = vehicle_baseline();
            tire = tire_load_sensitive_baseline();
            aero = aero_baseline();
            powertrain = powertrain_emrax228_hvcc_demo();
            brake = brake_baseline();
            coarseOptions = default_qss_options();
            coarseOptions.v_grid_mps = (0:1:45).';
            coarseOptions.ay_grid_g = -4:0.1:4;
            fineOptions = coarseOptions;
            fineOptions.v_grid_mps = (0:0.5:45).';
            fineOptions.ay_grid_g = -4:0.05:4;

            testCase.CoarseGgv = generate_model_ggv(vehicle, tire, aero, ...
                powertrain, brake, coarseOptions);
            coarseModels.ggv = testCase.CoarseGgv;
            testCase.CoarseResult = run_qss_lap(track, vehicle, ...
                coarseModels, coarseOptions);
            mirroredTrack = track;
            mirroredTrack.kappa_1pm = -track.kappa_1pm;
            testCase.MirrorResult = run_qss_lap(mirroredTrack, vehicle, ...
                coarseModels, coarseOptions);

            fineGgv = generate_model_ggv(vehicle, tire, aero, ...
                powertrain, brake, fineOptions);
            fineModels.ggv = fineGgv;
            testCase.FineResult = run_qss_lap(track, vehicle, ...
                fineModels, fineOptions);

            ay_g = testCase.CoarseResult.ay_mps2 ...
                / coarseOptions.gravity_mps2;
            caps = arrayfun(@(speed, lateral) interp_ggv( ...
                testCase.CoarseGgv, speed, lateral, coarseOptions), ...
                testCase.CoarseResult.v_mps, ay_g);
            testCase.AxMinimum_mps2 = reshape( ...
                [caps.ax_min_mps2], [], 1);
            testCase.AxMaximum_mps2 = reshape( ...
                [caps.ax_max_mps2], [], 1);
            testCase.IsFeasible = reshape([caps.is_feasible], [], 1);
            tolerance_mps2 = coarseOptions.accel_tolerance_mps2;
            testCase.IsAtLongitudinalBoundary = ...
                abs(testCase.CoarseResult.ax_mps2 ...
                - testCase.AxMinimum_mps2) <= tolerance_mps2 ...
                | abs(testCase.CoarseResult.ax_mps2 ...
                - testCase.AxMaximum_mps2) <= tolerance_mps2;
            longitudinalLabels = ["traction", "tire", "torque", ...
                "power", "top_speed", "brake_traction_bias", ...
                "brake_mechanical", "brake_disabled", ...
                "front_axle_lift", "rear_axle_lift", "measured"];
            testCase.ReportsLongitudinalLimiter = ismember( ...
                testCase.CoarseResult.limiter, longitudinalLabels);
        end
    end

    methods (Test, TestTags={'Benchmark'})
        function testCurvatureMirrorSymmetry(testCase)
            testCase.verifyEqual(testCase.MirrorResult.lap_time_s, ...
                testCase.CoarseResult.lap_time_s, AbsTol=1e-8);
            testCase.verifyEqual(testCase.MirrorResult.v_mps, ...
                testCase.CoarseResult.v_mps, AbsTol=1e-7);
            testCase.verifyEqual(testCase.MirrorResult.ax_mps2, ...
                testCase.CoarseResult.ax_mps2, AbsTol=1e-6);
            testCase.verifyEqual(testCase.MirrorResult.ay_mps2, ...
                -testCase.CoarseResult.ay_mps2, AbsTol=1e-6);
        end

        function testCompleteLapRemainsInsideGgv(testCase)
            result = testCase.CoarseResult;
            testCase.verifyTrue(all(testCase.IsFeasible));
            testCase.verifyLessThanOrEqual(result.ax_mps2, ...
                testCase.AxMaximum_mps2 + 1e-6);
            testCase.verifyGreaterThanOrEqual(result.ax_mps2, ...
                testCase.AxMinimum_mps2 - 1e-6);
            testCase.verifyLessThanOrEqual(result.v_mps, ...
                result.v_lateral_limit_mps + 1e-7);
            testCase.verifyTrue(result.solver.converged);
        end

        function testCanonicalGgvHasValidFeasibleDomain(testCase)
            ggv = testCase.CoarseGgv;
            testCase.verifyTrue(all(ggv.solve_converged_accel( ...
                ggv.feasible)));
            testCase.verifyTrue(all(ggv.solve_converged_brake( ...
                ggv.feasible)));
            testCase.verifyLessThanOrEqual(max(abs( ...
                ggv.solve_residual_accel_mps2(ggv.feasible))), ...
                ggv.options.ggv_tolerance_mps2 + 1e-12);
            testCase.verifyLessThanOrEqual(max(abs( ...
                ggv.solve_residual_brake_mps2(ggv.feasible))), ...
                ggv.options.ggv_tolerance_mps2 + 1e-12);
            testCase.verifyFalse(any(ggv.lateral_limit_truncated, "all"));
            testCase.verifyFalse(any(ggv.wheel_lift(ggv.feasible)));
        end

        function testGgvGridRefinementConverges(testCase)
            relativeDifference = abs(testCase.FineResult.lap_time_s ...
                - testCase.CoarseResult.lap_time_s) ...
                / testCase.FineResult.lap_time_s;
            testCase.verifyLessThan(relativeDifference, 0.002);
        end

        function testReportedLongitudinalLimitersAreActive(testCase)
            testCase.verifyTrue(all( ...
                ~testCase.ReportsLongitudinalLimiter ...
                | testCase.IsAtLongitudinalBoundary));
        end
    end
end
